UNION ALL

SELECT 'STORE_SPATIAL_ANALYSIS',
       COUNT(*)
FROM STORE_SPATIAL_ANALYSIS

UNION ALL

SELECT 'STORE_OPPORTUNITY_ANALYSIS',
       COUNT(*)
FROM STORE_OPPORTUNITY_ANALYSIS

UNION ALL

SELECT 'STORE_PERFORMANCE_ANALYSIS',
       COUNT(*)
FROM STORE_PERFORMANCE_ANALYSIS;


SELECT
    COUNT(*) AS TOTAL_RECORDS,
    COUNT(DISTINCT PING_ID) AS UNIQUE_PINGS
FROM MOBILITY_PINGS_FEATURED;

SELECT
    MOVEMENT_TYPE,
    COUNT(*) AS MOBILITY_COUNT
FROM MOBILITY_PINGS_FEATURED
GROUP BY MOVEMENT_TYPE
ORDER BY MOBILITY_COUNT DESC;

