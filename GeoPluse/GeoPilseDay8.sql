USE SCHEMA ANALYTICS;

CREATE OR REPLACE VIEW STORE_PERFORMANCE_VIEW AS
SELECT
    OPPORTUNITY_RANK,
    NEAREST_STORE_ID,
    NEAREST_STORE_NAME,
    STORE_TYPE,
    OPPORTUNITY_SCORE,
    MOBILITY_INTENSITY_SCORE,
    CATCHMENT_SCORE,
    CAPACITY_PRESSURE_SCORE,
    CANNIBALIZATION_INDICATOR,
    NEARBY_STORE_COUNT
FROM GEOPULSE_DB.RAW.STORE_OPPORTUNITY_ANALYSIS;

SELECT *
FROM STORE_PERFORMANCE_VIEW
ORDER BY OPPORTUNITY_SCORE DESC;

SELECT
    CURRENT_DATABASE() AS DATABASE_NAME,
    CURRENT_SCHEMA() AS SCHEMA_NAME;

    SELECT COUNT(*) AS ANALYTICS_VIEW_ROWS
FROM STORE_PERFORMANCE_VIEW;

